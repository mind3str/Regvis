  /* ---------------- URL state ---------------- */
  function writeHash() {
    var parts = [];
    GROUPS.forEach(function (g) {
      var K = KEY[g], ix = function (l) { return l === NONE ? "n" : LABELS[g].indexOf(l); };
      if (state.inc[g].size) parts.push("i" + K + "=" + Array.from(state.inc[g]).map(ix).join("."));
      if (state.exc[g].size) parts.push("x" + K + "=" + Array.from(state.exc[g]).map(ix).join("."));
      if (state.all[g]) parts.push("all" + K + "=1");
    });
    if (state.from !== Y0 || state.to !== Y1) parts.push("y=" + state.from + "-" + state.to);
    if (state.title) parts.push("t=" + encodeURIComponent(d3.select("#q-title").property("value").trim()));
    if (state.author) parts.push("a=" + encodeURIComponent(d3.select("#q-author").property("value").trim()));
    if (state.sort !== "year") parts.push("s=" + state.sort);
    if (state.view !== "grid") parts.push("v=" + state.view);
    if (state.open) parts.push("p=" + state.open);
    var h = parts.length ? "#" + parts.join("&") : "";
    if (location.hash !== h) history.replaceState(null, "", location.pathname + location.search + h);
  }
  function readHash() {
    var BYK = {};
    GROUPS.forEach(function (g) { BYK[KEY[g]] = g; });
    location.hash.replace(/^#/, "").split("&").forEach(function (kv) {
      if (!kv) return;
      var i = kv.indexOf("="), k = kv.slice(0, i), v = decodeURIComponent(kv.slice(i + 1)), g;
      if ((k[0] === "i" || k[0] === "x") && (g = BYK[k.slice(1)])) {
        v.split(".").forEach(function (n) { var l = n === "n" ? NONE : LABELS[g][+n]; if (l) (k[0] === "i" ? state.inc : state.exc)[g].add(l); });
      } else if (k.slice(0, 3) === "all" && (g = BYK[k.slice(3)])) state.all[g] = true;
      else if (k === "y") { var yy = v.split("-"); state.from = Math.max(Y0, +yy[0] || Y0); state.to = Math.min(Y1, +yy[1] || Y1); }
      else if (k === "t") { d3.select("#q-title").property("value", v); state.title = norm(v); }
      else if (k === "a") { d3.select("#q-author").property("value", v); state.author = norm(v); }
      else if (k === "s" && /^(year|title|level)$/.test(v)) state.sort = v;
      else if (k === "v" && /^(grid|table)$/.test(v)) state.view = v;
      else if (k === "p" && BY_ID.has(v)) state.open = v;
    });
  }

